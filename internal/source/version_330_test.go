package source

import "testing"

// 0.6.330：版本比较唯一实现的语义矩阵。
// 每一行都对应一个真实踩过或可预见的升级判定场景。
func TestCompareVersionMatrix(t *testing.T) {
	cases := []struct {
		name string
		a, b string
		want int
	}{
		// ── 基础 ─────────────────────────────────────────────
		{"相等", "1.0.0", "1.0.0", 0},
		{"v 前缀", "v1.2.3", "1.2.3", 0},
		{"大写 V", "V1.2.3", "v1.2.3", 0},
		{"数字段非字典序", "1.10.0", "1.9.0", 1},
		{"多一位核心段", "4.1.3.4", "4.1.3", 1},
		{"段数零填充", "1.0", "1.0.0", 0},
		{"前导零", "01.2", "1.2", 0},

		// ── 数字修订号（本次事故）───────────────────────────
		{"修订号递增", "1.13.0-1", "1.13.0", 1},
		{"修订号反向", "1.13.0", "1.13.0-1", -1},
		{"修订号同值", "1.13.0-1", "1.13.0-1", 0},
		{"两位修订号", "1.0.0-10", "1.0.0-9", 1}, // 旧实现字符串比 → -1（装不上）
		{"两位修订号反向", "1.0.0-9", "1.0.0-10", -1},
		{"修订号 0 等同", "1.0.0-0", "1.0.0", 0},

		// ── 预发布 ───────────────────────────────────────────
		{"预发布低于正式", "1.0.0-rc.1", "1.0.0", -1},
		{"正式高于预发布", "1.0.0", "1.0.0-rc.1", 1},
		{"预发布递增", "1.0.0-rc.38", "1.0.0-rc.37", 1}, // 旧实现两边都剥成 1.0.0 → 0（漏更新）
		{"预发布递减", "1.0.0-rc.36", "1.0.0-rc.37", -1},
		{"rc 无点号形式", "2.0.0-rc2", "2.0.0-rc1", 1},
		{"beta 递增", "2.0.0-beta2", "2.0.0-beta10", -1},
		{"alpha < beta", "2.0.0-alpha", "2.0.0-beta", -1},
		{"预发布 < 修订号", "1.0.0-rc.1", "1.0.0-1", -1},
		{"_rc 形式", "1.0.0_rc3", "1.0.0", -1},

		// ── 既有契约 ─────────────────────────────────────────
		{"下划线 Java 系", "1.8.0_99", "1.8.0_100", -1},
		{"下划线长号", "1.8.0_492", "1.8.0_500", -1},
		{"v 与多位数", "v2.0.0", "10.0.0", -1},
		{"v 与多位数反向", "v10.0.0", "2.0.0", 1},
		{"版本串前缀", "4.8.8-1", "4.8.9", -1},
		{"版本串同底修订", "4.8.8-1", "4.8.8-2", -1},

		// ── 噪声后缀 ─────────────────────────────────────────
		{"架构后缀忽略", "1.0.0-x86", "1.0.0", 0},
		{"panel 后缀忽略", "1.0.0-panel", "1.0.0", 0},
		{"build 元数据忽略", "1.0.0+build5", "1.0.0", 0},
		{"stable 尾巴忽略", "2.4.0.1_stable_2026-10-07", "2.4.0.1", 0},

		// ── 不可解析（不判更新）──────────────────────────────
		{"空串", "", "1.0.0", 0},
		{"纯字母", "abc", "1.0.0", 0},
		{"标签前缀 latest", "latest-2026.10.17", "4.1.3.4", 0}, // 不可比 → 不产生假更新
		{"标签前缀 release", "release-2026.10.17", "2026.10.17", 0},
		{"latest-full", "latest-full", "1.0.0", 0},
		{"畸形段", "1..2", "1.2", 0},
	}
	for _, c := range cases {
		if got := CompareVersion(c.a, c.b); got != c.want {
			t.Errorf("%s: CompareVersion(%q,%q) = %d, want %d", c.name, c.a, c.b, got, c.want)
		}
		// 反对称性：反向必须取相反数（排序稳定性依赖它）
		if got := CompareVersion(c.b, c.a); got != -c.want {
			t.Errorf("%s: 反对称性破坏 CompareVersion(%q,%q) = %d, want %d", c.name, c.b, c.a, got, -c.want)
		}
	}
}

// ParseVersion 的可解析性必须与 api 的 comparableVersion 口径一致（见 api 侧对照表）。
func TestParseVersionOK(t *testing.T) {
	ok := []string{"1", "1.9.0", "v2.5.0", "1.0.0-1", "1.9.0-rc1", "1.8.0_rc", "1.8.0_492", "V2.0.0-RC1"}
	bad := []string{"", "   ", "abc", "1.2.x", "1..2", "1.2.", "latest-2026.10.17", "release-1.2.3"}
	for _, v := range ok {
		if !ParseVersion(v).OK {
			t.Errorf("ParseVersion(%q).OK = false, want true", v)
		}
	}
	for _, v := range bad {
		if ParseVersion(v).OK {
			t.Errorf("ParseVersion(%q).OK = true, want false", v)
		}
	}
}
